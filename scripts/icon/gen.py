def circle(cx, cy, r):
    return f"M{cx - r},{cy}a{r},{r} 0 1 0 {2 * r},0a{r},{r} 0 1 0 {-2 * r},0z"


def layers():
    """(path, fill, stroke, strokeWidth, clipped) in paint order for the foreground."""
    out = [(FRAME, 'a1_800', None, 0, False), (SCREEN, 'a1_10', None, 0, False)]
    out += [(roof(a), k, None, 0, True) for a, k in ROOFS]
    out += [(PILL, 'a1_800', None, 0, False),
            (circle(*RING_C, RING_R), None, 'a1_50', 1.8, False),
            (circle(*RING_C, DOT_R), 'a1_800', None, 0, False),
            (HAND, 'n1_10', None, 0, False)]
    return out


def svg(size=512, bg=True, mask=False):
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">',
         f'<defs><clipPath id="s"><path d="{SCREEN}"/></clipPath></defs>']
    if bg:
        o.append(f'<rect width="108" height="108" fill="{PAL["a1_100"]}"/>')
    o.append(f'<g transform="translate(54 54) scale({SCALE}) translate(-54 -54)">')
    for d, fill, stroke, w, clip in layers():
        attrs = f'fill="{PAL[fill]}"' if fill else 'fill="none"'
        if stroke:
            attrs += f' stroke="{PAL[stroke]}" stroke-width="{w}"'
        el = f'<path d="{d}" {attrs}/>'
        o.append(f'<g clip-path="url(#s)">{el}</g>' if clip else el)
    o.append('</g></svg>')
    return '\n'.join(o)


def vector():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<!-- Phone screen with a pill notch, bands spreading down from it, a touch ring and a pointing hand.',
         '     Monet colors (system_accent1_*), generated by scripts/icon/gen.py. -->',
         '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
         '    android:width="108dp" android:height="108dp"',
         '    android:viewportWidth="108" android:viewportHeight="108">', GROUP]
    clip_open = False
    for d, fill, stroke, w, clip in layers():
        if clip and not clip_open:
            o.append('    <group>')
            o.append(f'        <clip-path android:pathData="{SCREEN}" />')
            clip_open = True
        if not clip and clip_open:
            o.append('    </group>')
            clip_open = False
        ind = '        ' if clip else '    '
        a = f'android:fillColor="@android:color/{ANDROID[fill]}"' if fill else ''
        if stroke:
            a += f'android:strokeColor="@android:color/{ANDROID[stroke]}" android:strokeWidth="{w}"'
        o.append(f'{ind}<path {a}\n{ind}    android:pathData="{d}" />')
    if clip_open:
        o.append('    </group>')
    o.append('    </group>')
    o.append('</vector>')
    return '\n'.join(o) + '\n'


def monochrome():
    # Alpha-only: frame outline, notch, ring and hand; bands as fading strokes.
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<!-- Themed-icon layer (Android 13+): only alpha matters, the launcher applies its own tint. -->',
         '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
         '    android:width="108dp" android:height="108dp"',
         '    android:viewportWidth="108" android:viewportHeight="108">', GROUP,
         f'    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd"\n        android:pathData="{FRAME} {SCREEN}" />',
         f'    <path android:fillColor="#FFFFFFFF" android:pathData="{PILL}" />',
         '    <group>',
         f'        <clip-path android:pathData="{SCREEN}" />']
    for i, (a, _) in enumerate(ROOFS[:4]):
        alpha = [0.35, 0.5, 0.7, 0.9][i]
        o.append(f'        <path android:strokeColor="#FFFFFFFF" android:strokeAlpha="{alpha}" android:strokeWidth="2"'
                 f'\n            android:pathData="M33,{a + 13}L54,{a + 1}L75,{a + 13}" />')
    o.append('    </group>')
    o.append(f'    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="1.8" android:pathData="{circle(*RING_C, RING_R)}" />')
    o.append(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{HAND}" />')
    o.append('    </group>')
    o.append('</vector>')
    return '\n'.join(o) + '\n'


STAT_GROUP = 'android:scaleX="2.3" android:scaleY="2.3" android:pivotX="54" android:pivotY="56" android:translateY="-2"'
STAT_PATHS = [(PILL, None), (circle(*RING_C, RING_R), 1.8), (HAND, None)]


