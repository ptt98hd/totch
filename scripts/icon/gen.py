#!/usr/bin/env python3
"""Black hole launcher icon (ui spec — Icon, FR-U33).

Writes the adaptive icon layers, the notification icon, SVG previews and the F-Droid icon.png from one geometry:
every circle is centred on (54, 54) and the accretion disk is a horizontal lens. Colours are Monet system colours, so
the launcher icon follows the wallpaper; previews use a fixed purple palette.

    python3 scripts/icon/gen.py          # from the repository root; needs ImageMagick (`magick`) for icon.png
"""
import math
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res/drawable"
HERE = ROOT / "scripts/icon"
FASTLANE_ICON = ROOT / "fastlane/metadata/android/en-US/images/icon.png"

C = 54.0            # centre of the 108 viewport
RING_OUT = 20.5     # lensed glow, outer radius
RING_IN = 14.5      # event horizon radius = inner edge of the glow
DISK_HALF = 32.4    # disk spans x = C ± DISK_HALF
DISK_SAG = 2.6      # half thickness of the disk at x = C
GAP = 1.2           # space between the disk and the glow

# Disk edges are arcs of one large radius; the cut in the glow follows the same arcs, GAP further out.
DISK_R = (DISK_HALF ** 2 + DISK_SAG ** 2) / (2 * DISK_SAG)
CUT_R = DISK_R + GAP
TOP_CENTRE_Y = C - DISK_SAG + DISK_R  # centre of the top edge arc (below the icon)

# Monet role -> (Android colour resource, preview colour)
COLORS = {
    "space": ("@android:color/system_accent1_800", "#381E72"),
    "star": ("@android:color/system_accent1_200", "#D0BCFF"),
    "glow": ("@android:color/system_accent1_200", "#D0BCFF"),
    "disk": ("@android:color/system_accent1_100", "#EADDFF"),
    "horizon": ("@android:color/system_neutral1_1000", "#000000"),
}

STARS = ("M33.5 30.1Q34.044 32.956 36.9 33.5Q34.044 34.044 33.5 36.9Q32.956 34.044 30.1 33.5Q32.956 32.956 33.5 30.1Z"
         "M75 71.8Q75.352 73.648 77.2 74Q75.352 74.352 75 76.2Q74.648 74.352 72.8 74Q74.648 73.648 75 71.8Z"
         "M73.1 33a0.9 0.9 0 1 0 1.8 0a0.9 0.9 0 1 0 -1.8 0Z")


def f(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def cut_points(r):
    """Where the upper cut arc meets the circle of radius r around the centre: (dx, y)."""
    # (y - C)^2 + dx^2 = r^2 and (y - TOP_CENTRE_Y)^2 + dx^2 = CUT_R^2, both centred on x = C.
    d = TOP_CENTRE_Y - C
    y = C + (r * r - CUT_R * CUT_R + d * d) / (2 * d)
    return math.sqrt(r * r - (y - C) ** 2), y


def glow():
    """Top and bottom arches of the glow ring, mirror images across y = C."""
    dxo, yo = cut_points(RING_OUT)
    dxi, yi = cut_points(RING_IN)
    top = (f"M{f(C - dxo)} {f(yo)}A{f(RING_OUT)} {f(RING_OUT)} 0 0 1 {f(C + dxo)} {f(yo)}"
           f"A{f(CUT_R)} {f(CUT_R)} 0 0 0 {f(C + dxi)} {f(yi)}"
           f"A{f(RING_IN)} {f(RING_IN)} 0 0 0 {f(C - dxi)} {f(yi)}"
           f"A{f(CUT_R)} {f(CUT_R)} 0 0 0 {f(C - dxo)} {f(yo)}Z")
    byo, byi = 2 * C - yo, 2 * C - yi
    bottom = (f"M{f(C - dxo)} {f(byo)}A{f(RING_OUT)} {f(RING_OUT)} 0 0 0 {f(C + dxo)} {f(byo)}"
              f"A{f(CUT_R)} {f(CUT_R)} 0 0 1 {f(C + dxi)} {f(byi)}"
              f"A{f(RING_IN)} {f(RING_IN)} 0 0 1 {f(C - dxi)} {f(byi)}"
              f"A{f(CUT_R)} {f(CUT_R)} 0 0 1 {f(C - dxo)} {f(byo)}Z")
    return top + bottom


def horizon():
    r = RING_IN
    return f"M{f(C - r)} {f(C)}a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0Z"


def disk():
    left, right = f(C - DISK_HALF), f(C + DISK_HALF)
    r = f(DISK_R)
    return f"M{left} {f(C)}A{r} {r} 0 0 1 {right} {f(C)}A{r} {r} 0 0 1 {left} {f(C)}Z"


def foreground_layers():
    return [("glow", glow(), "Lensed glow around the shadow: top and bottom arches"),
            ("horizon", horizon(), "Event horizon"),
            ("disk", disk(), "Accretion disk crossing in front, horizontal")]


def vector(paths, comment, extra_attrs="", size="108dp"):
    out = ['<?xml version="1.0" encoding="utf-8"?>']
    if comment:
        out.append(f"<!-- {comment} Generated by scripts/icon/gen.py. -->")
    out.append('<vector xmlns:android="http://schemas.android.com/apk/res/android"')
    out.append(f'    android:width="{size}"\n    android:height="{size}"')
    out.append('    android:viewportWidth="108"\n    android:viewportHeight="108"' + extra_attrs + ">")
    for fill, data, note in paths:
        if note:
            out.append(f"    <!-- {note} -->")
        out.append(f'    <path\n        android:fillColor="{fill}"\n        android:pathData="{data}" />')
    out.append("</vector>\n")
    return "\n".join(out)


def svg(parts, background=True):
    o = ['<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1080" viewBox="0 0 108 108">']
    if background:
        o.append(f'<rect width="108" height="108" fill="{COLORS["space"][1]}"/>')
        o.append(f'<path d="{STARS}" fill="{COLORS["star"][1]}"/>')
    o += [f'<path d="{d}" fill="{fill}"/>' for fill, d in parts]
    o.append("</svg>\n")
    return "".join(o)


def main():
    layers = foreground_layers()
    (RES / "ic_launcher_background.xml").write_text(vector(
        [(COLORS["space"][0], "M0,0h108v108h-108z", "Deep space (Monet)"),
         (COLORS["star"][0], STARS, "Stars, inside the 66 dp safe zone")],
        "Black hole icon background (FR-U33)."))
    (RES / "ic_launcher_foreground.xml").write_text(vector(
        [(COLORS[role][0], d, note) for role, d, note in layers],
        "Black hole centred on (54, 54) inside the 66 dp safe zone (FR-U33)."))
    mono = [(r, d, n) for r, d, n in layers if r != "horizon"]
    (RES / "ic_launcher_monochrome.xml").write_text(vector(
        [("#FFFFFF", d, n) for _, d, n in mono],
        "Themed icon: alpha only, the system tints it."))
    stat = vector([("#FFFFFFFF", d, None) for _, d, _ in mono],
                  "Notification small icon: the monochrome black hole, enlarged.",
                  '\n    android:tint="?android:attr/colorControlNormal"', size="24dp")
    # Enlarged around the centre: the disk alone is 65 of 108 units wide.
    stat = stat.replace("    <path", "    <group android:scaleX=\"1.6\" android:scaleY=\"1.6\" android:pivotX=\"54\" android:pivotY=\"54\">\n    <path", 1)
    stat = stat.replace("</vector>", "    </group>\n</vector>")
    (RES / "ic_stat_totch.xml").write_text(stat)

    preview = [(COLORS[role][1], d) for role, d, _ in layers]
    (HERE / "background.svg").write_text(svg([]))
    (HERE / "foreground.svg").write_text(svg(preview, background=False))
    (HERE / "monochrome.svg").write_text(svg([("#000000", d) for _, d, _ in mono], background=False))
    (HERE / "full.svg").write_text(svg(preview))
    subprocess.run(["magick", "-background", "none", "-density", "96", str(HERE / "full.svg"),
                    "-resize", "512x512", str(FASTLANE_ICON)], check=True)


if __name__ == "__main__":
    main()
