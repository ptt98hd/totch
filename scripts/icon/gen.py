def roof(a):
    return f"M35,{a + 12}L54,{a}L73,{a + 12}V75H35z"


ROOFS = [(44, 'a1_200'), (48, 'a1_300'), (52, 'a1_400'), (56, 'a1_600'), (60, 'a1_800')]
